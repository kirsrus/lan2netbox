package store

import "github.com/rs/xid"

// NewID возвращает новый короткий глобально уникальный идентификатор (xid).
//
// xid — 12-байтовый идентификатор (20 символов base32), сортируемый
// по времени создания. Компактнее UUID (36 символов), не требует
// генератора в БД и подходит для распределённого обнаружения устройств:
// ID можно генерировать в любом компоненте без обращения к хранилищу.
//
// Используется в качестве первичного ключа таблиц mac и mac_ip.
func NewID() string {
	return xid.New().String()
}
